"""
Kinematic tractor-semitrailer model used to generate the Training-page backing diagrams.
World units: feet. x to the right, y DOWN (screen-style); heading angle t measured from +x toward +y
(so t=90deg points DOWN the page, and a LEFT turn for the driver DEcreases t).

Rig (matches the Trucking-page drawing):
  P  = kingpin / centre of the drive tandem (fifth wheel sits ~over the tandem centre)
  L1 = steer axle -> drive-tandem centre   = 20.3 ft (5th wheel over the tandem centre; trailer nose 5 ft behind the sleeper)
  L2 = kingpin -> trailer-tandem centre    = 42.0 ft  (kingpin 3 ft behind nose, tandem centre 45 ft from nose)
Trailer box: nose at +3 ft from P, rear at -50 ft (53 ft box), 8.5 ft wide. Reefer unit 2.2 ft deep on the nose.
Tractor: front bumper 23.4 ft ahead of P; rear of the cab fairings 6.5 ft ahead of P.

Method: a vehicle path is exactly reversible. So each diagram is generated by driving FORWARD out of the
finished (parked) position, then walking that same path in REVERSE. Every pose / arrow is therefore a
physically possible backing path, with no guessing about which way the trailer leans.
"""
import math

L1, L2 = 20.3, 42.0
W = 8.5
TR_NOSE, TR_REAR, REEFER = 3.0, -50.0, 2.2
TRACTOR_FRONT, CAB_BACK = L1 + 3.1, L1 - 13.8   # bumper 3.1 ft ahead of steer axle; CAB_BACK = rear edge of the cab FAIRINGS (sleeper back 12.3 ft + 1.5 ft fairings behind the steer axle)
DOCK_GAP = 0.5            # trailer rear sits 0.5 ft off the dock face (y=0)
BAY = 12.0                # door / stall spacing
NEIGHBOR_X = (-BAY, BAY)
# other trailers already parked along the same dock row (obstacles too, and drawn muted)
ROW_X = tuple(BAY * k for k in range(-3, 11) if k not in (-1, 0, 1))
NEIGHBOR_LEN = 53.0

def rad(d): return math.radians(d)
def deg(r): return math.degrees(r)

def start_state():
    # final parked pose: trailer pointing DOWN the page (t=90), rear at the dock
    return [0.0, DOCK_GAP - TR_REAR, rad(90), rad(90)]

def advance(s, delta_deg, dist, h=0.05):
    """move forward (dist>0) with steer angle delta (deg, +=right). returns list of states"""
    out = []
    n = max(1, int(abs(dist) / h))
    d = dist / n
    x, y, t1, t2 = s
    tand = math.tan(rad(delta_deg))
    for _ in range(n):
        # midpoint integration
        t1m = t1 + 0.5 * d * tand / L1
        t2m = t2 + 0.5 * d * math.sin(t1 - t2) / L2
        x += d * math.cos(t1m); y += d * math.sin(t1m)
        t1 += d * tand / L1
        t2 += d * math.sin(t1m - t2m) / L2
        out.append([x, y, t1, t2])
    return out

def rot(px, py, t):
    c, s = math.cos(t), math.sin(t)
    return (px * c - py * s, px * s + py * c)

REEFER_W = 6.8
def box(state, kind):
    x, y, t1, t2 = state
    if kind == "reefer":
        t, x0, x1 = t2, TR_NOSE, TR_NOSE + REEFER
        hw = REEFER_W / 2
        pts = [(x0, -hw), (x1, -hw), (x1, hw), (x0, hw)]
        return [(x + rot(px, py, t)[0], y + rot(px, py, t)[1]) for px, py in pts]
    if kind == "trailer":
        t, x0, x1 = t2, TR_REAR, TR_NOSE + REEFER
    elif kind == "cab":              # cab + hood (what the trailer must not touch)
        t, x0, x1 = t1, CAB_BACK, TRACTOR_FRONT
    else:                            # whole tractor
        t, x0, x1 = t1, -3.5, TRACTOR_FRONT
    hw = W / 2
    pts = [(x0, -hw), (x1, -hw), (x1, hw), (x0, hw)]
    return [(x + rot(px, py, t)[0], y + rot(px, py, t)[1]) for px, py in pts]

def neighbor(nx):
    hw = W / 2
    return [(nx - hw, DOCK_GAP), (nx + hw, DOCK_GAP), (nx + hw, DOCK_GAP + NEIGHBOR_LEN + REEFER), (nx - hw, DOCK_GAP + NEIGHBOR_LEN + REEFER)]

def _axes(poly):
    ax = []
    for i in range(len(poly)):
        a, b = poly[i], poly[(i + 1) % len(poly)]
        e = (b[0] - a[0], b[1] - a[1]); n = (-e[1], e[0]); l = math.hypot(*n)
        ax.append((n[0] / l, n[1] / l))
    return ax

def overlaps(p, q):
    for ax in _axes(p) + _axes(q):
        pp = [v[0] * ax[0] + v[1] * ax[1] for v in p]; qq = [v[0] * ax[0] + v[1] * ax[1] for v in q]
        if max(pp) < min(qq) or max(qq) < min(pp):
            return False
    return True

def _pt_seg(p, a, b):
    ax, ay = a; bx, by = b; px, py = p
    dx, dy = bx - ax, by - ay
    t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))

def distance(p, q):
    if overlaps(p, q): return 0.0
    d = 1e9
    for A, B in ((p, q), (q, p)):
        for v in A:
            for i in range(len(B)):
                d = min(d, _pt_seg(v, B[i], B[(i + 1) % len(B)]))
    return d

def audit(states, extra_obstacles=()):
    """min clearance (ft) of trailer & tractor vs the two parked trailers, dock wall, plus max articulation"""
    obs = [neighbor(nx) for nx in NEIGHBOR_X + ROW_X] + list(extra_obstacles)
    mc, art, wall = 1e9, 0, 1e9
    for s in states:
        for kind in ("trailer", "tractor"):
            b = box(s, kind)
            for o in obs:
                mc = min(mc, distance(b, o))
            wall = min(wall, min(v[1] for v in b))
        # trailer vs cab (self-collision / jackknife)
        if overlaps(box(s, "reefer"), box(s, "cab")) or overlaps(box(s, "trailer"), box(s, "cab")) and False: mc = 0.0
        art = max(art, abs(deg(s[2] - s[3])))
    return dict(min_clearance_ft=round(mc, 2), max_articulation_deg=round(art, 1), min_y_ft=round(wall, 2))

def run(schedule):
    """schedule: list of ('straight', dist) | ('turn', delta_deg, until_fn) | ('turn_dist', delta_deg, dist)"""
    s = start_state(); states = [list(s)]; steer = [0.0]
    for seg in schedule:
        if seg[0] == "straight":
            new = advance(s, 0.0, seg[1]); d = 0.0
        elif seg[0] == "turn_dist":
            new = advance(s, seg[1], seg[2]); d = seg[1]
        else:  # turn until condition
            new = []; d = seg[1]; cur = s
            for _ in range(6000):
                nxt = advance(cur, d, 0.25)
                new += nxt; cur = nxt[-1]
                if seg[2](cur): break
        states += new; steer += [d] * len(new); s = states[-1]
    return states, steer


def back_control(s, Kp=2.2, kt=0.06, k1=0.10, max_art=55, max_steer=32, target_x=0.0):
    """Cascaded backing controller (what a good driver does: aim the trailer, then steer to get the angle).
       returns steer angle in degrees (+ = right) for BACKING (distance travelled backwards)."""
    x, y, t1, t2 = s
    ax, ay = x - L2 * math.cos(t2), y - L2 * math.sin(t2)          # trailer tandem centre
    e = ax - target_x                                                # +ve: east of the stall centre-line
    # desired trailer heading: 90deg (pointing down the page) corrected toward the centre-line
    # while backing, pointing the trailer nose a bit toward the side the axle must come FROM pulls it back
    corr = max(-60, min(60, Kp * e * (1.0 if ay > 70 else 0.0 if False else 1.0)))
    t2_des = rad(90) - rad(corr)
    err2 = t2_des - t2
    # backing: dt2/ds' = -sin(t1-t2)/L2  ->  sin(t1-t2) = -L2*kt*err2
    gam = math.asin(max(-0.95, min(0.95, -L2 * kt * err2)))
    gam = max(-rad(max_art), min(rad(max_art), gam))
    t1_des = t2 + gam
    # backing: dt1/ds' = -tan(delta)/L1 -> tan(delta) = -L1*k1*(t1_des - t1)
    d = math.degrees(math.atan(-L1 * k1 * (t1_des - t1)))
    return max(-max_steer, min(max_steer, d))

def back_in(start, ds=0.25, max_len=420):
    """simulate backing with the controller until the trailer rear touches the dock gap. returns states list, steer list"""
    s = list(start); states = [list(s)]; steer = []
    for _ in range(int(max_len / ds)):
        d = back_control(s)
        nxt = advance(s, d, -ds, h=ds)[-1]
        steer.append(d); states.append(nxt); s = nxt
        rear_y = s[1] + (TR_REAR) * math.sin(s[3])
        if rear_y <= DOCK_GAP + 0.01: break
        if any(abs(v) > 1e4 for v in s): break
    return states, steer

def final_error(states):
    x, y, t1, t2 = states[-1]
    rx, ry = x + TR_REAR * math.cos(t2), y + TR_REAR * math.sin(t2)
    return dict(rear_x=round(rx, 2), rear_y=round(ry, 2), t2=round(deg(t2) % 360, 1), t1=round(deg(t1) % 360, 1))

def pose_from_rear(rx, ry, t1_deg, t2_deg):
    """build a state from the trailer-rear-centre position and the two headings"""
    t2 = rad(t2_deg)
    return [rx - TR_REAR * math.cos(t2), ry - TR_REAR * math.sin(t2), rad(t1_deg), t2]


# ---------------------------------------------------------------------------------------------
# Flat-output planner: choose a smooth path for the trailer's tandem centre A, derive everything else.
#   e2 = unit vector along trailer heading;  backing => A moves along -e2.
#   kappa = d(t2)/ds along A's path;  tan(gamma) = -L2*kappa   (gamma = t1 - t2)
#   P = A + L2*e2 (kingpin);   t1 = t2 + gamma;   tan(delta) = -L1 * d(t1)/ds_P   (backing)
# ---------------------------------------------------------------------------------------------
def _quintic(p0, v0, p1, v1, u):
    # quintic Hermite with zero acceleration at both ends
    h00 = 1 - 10*u**3 + 15*u**4 - 6*u**5; h10 = u - 6*u**3 + 8*u**4 - 3*u**5; h20 = 0.5*u**2 - 1.5*u**3 + 1.5*u**4 - 0.5*u**5
    h01 = 10*u**3 - 15*u**4 + 6*u**5;     h11 = -4*u**3 + 7*u**4 - 3*u**5;   h21 = 0.5*u**3 - u**4 + 0.5*u**5
    return tuple(h00*p0[i] + h10*v0[i] + h01*p1[i] + h11*v1[i] for i in range(2))

def plan_backing(P0, t2_0_deg, M0, M1, n=1500, extra_straight=0.0):
    """P0: kingpin start (x,y) with the whole rig straight (gamma=0) at trailer heading t2_0.
       M0/M1: path 'stiffness' (larger = straighter near the ends). Final: trailer in stall, heading 90deg."""
    t20 = rad(t2_0_deg)
    A0 = (P0[0] - L2*math.cos(t20), P0[1] - L2*math.sin(t20))
    A1 = (0.0, DOCK_GAP - TR_REAR + L2 + 0.0)  # kingpin at y=50.5 -> A at 8.5
    A1 = (0.0, DOCK_GAP + (-TR_REAR) - L2)
    v0 = (-math.cos(t20)*M0, -math.sin(t20)*M0)
    v1 = (0.0, -M1)
    pts = [_quintic(A0, v0, A1, v1, i/n) for i in range(n+1)]
    # headings, curvature (per unit arc length of A)
    t2 = []; s = [0.0]
    for i in range(n+1):
        a, b = pts[max(0, i-1)], pts[min(n, i+1)]
        dx, dy = b[0]-a[0], b[1]-a[1]
        t2.append(math.atan2(-dy, -dx))          # e2 = -tangent
    # unwrap
    for i in range(1, n+1):
        while t2[i]-t2[i-1] > math.pi: t2[i] -= 2*math.pi
        while t2[i]-t2[i-1] < -math.pi: t2[i] += 2*math.pi
    for i in range(1, n+1): s.append(s[-1] + math.hypot(pts[i][0]-pts[i-1][0], pts[i][1]-pts[i-1][1]))
    kappa = [0.0]*(n+1)
    for i in range(1, n):
        kappa[i] = (t2[i+1]-t2[i-1])/(s[i+1]-s[i-1])
    kappa[0], kappa[n] = kappa[1], kappa[n-1]
    gam = [-math.atan(L2*k) for k in kappa]
    t1 = [t2[i] + gam[i] for i in range(n+1)]
    Pk = [(pts[i][0] + L2*math.cos(t2[i]), pts[i][1] + L2*math.sin(t2[i])) for i in range(n+1)]
    # steering
    steer = [0.0]*(n+1)
    for i in range(1, n):
        dsP = math.hypot(Pk[i+1][0]-Pk[i-1][0], Pk[i+1][1]-Pk[i-1][1])
        steer[i] = deg(math.atan(-L1 * (t1[i+1]-t1[i-1]) / dsP))
    steer[0], steer[n] = steer[1], steer[n-1]
    states = [[Pk[i][0], Pk[i][1], t1[i], t2[i]] for i in range(n+1)]
    return states, steer, s

def verify_by_integration(states, steer):
    """re-drive the true kinematic model with only the planned steering; report max pose error vs the plan"""
    cur = list(states[0]); worst_pos, worst_ang = 0.0, 0.0
    for i in range(1, len(states)):
        dsP = math.hypot(states[i][0]-states[i-1][0], states[i][1]-states[i-1][1])
        cur = advance(cur, steer[i], -dsP, h=max(0.02, dsP/3))[-1]
        worst_pos = max(worst_pos, math.hypot(cur[0]-states[i][0], cur[1]-states[i][1]))
        worst_ang = max(worst_ang, abs(deg(cur[2]-states[i][2])), abs(deg(cur[3]-states[i][3])))
    return round(worst_pos, 2), round(worst_ang, 2)
